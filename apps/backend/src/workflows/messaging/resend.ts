import { MedusaError, Modules } from "@medusajs/framework/utils"
import {
  StepResponse,
  WorkflowResponse,
  createStep,
  createWorkflow,
  transform,
} from "@medusajs/framework/workflows-sdk"
import { ConflictError, ValidationError } from "../../lib/errors"
import type { MessageChannel } from "../../lib/messaging/recipients"
import type { MessageTemplateName } from "../../lib/messaging/templates"
import { RESENDABLE_TEMPLATES, orderMessageResources } from "./history"
import { sendMessageStep } from "./send-message"
import type { SendMessageInput } from "./send-message"

/** One message again in ten minutes: a mail box flooded by the shop's mistake helps no one. */
export const RESEND_GAP_MS = 10 * 60 * 1000

export interface ResendOrderMessageInput {
  order_id: string
  /** The notification (a row of the order's history) to send again. */
  message_id: string
}

interface NotificationRow {
  id: string
  template?: string | null
  channel: string
  resource_id?: string | null
  status?: string | null
  created_at: string | Date
}

/** What Medusa's notification service lists (2.21.2, generated by MedusaService). */
interface NotificationRows {
  listNotifications: (
    filters: Record<string, unknown>,
    config: { take: number; select: string[]; order?: Record<string, "ASC" | "DESC"> }
  ) => Promise<NotificationRow[]>
}

/**
 * Which message to send again, and on which channel: one of the order's
 * own (its, its parcels', its invoices'), of a template that may go again,
 * not sent within ten minutes. Reads only: nothing to undo.
 */
const resolveResendStep = createStep(
  "messaging-resolve-resend",
  async (input: ResendOrderMessageInput, { container }) => {
    const resources = await orderMessageResources(container, input.order_id)
    const rows = container.resolve(Modules.NOTIFICATION) as unknown as NotificationRows
    const select = ["id", "template", "channel", "resource_id", "status", "created_at"]
    const [message] = await rows.listNotifications({ id: input.message_id }, { take: 1, select })
    if (!message?.resource_id || !resources.includes(message.resource_id)) {
      throw new MedusaError(MedusaError.Types.NOT_FOUND, "messages.unknown")
    }
    const template = message.template ?? ""
    const channel: MessageChannel = message.channel === "sms" ? "sms" : "email"
    if (!RESENDABLE_TEMPLATES.has(template) || message.status === "pending") {
      throw new ValidationError("messages.not_resendable")
    }
    const [latest] = await rows.listNotifications(
      { template, resource_id: message.resource_id, channel },
      { take: 1, select, order: { created_at: "DESC" } }
    )
    if (latest && Date.now() - new Date(latest.created_at).getTime() < RESEND_GAP_MS) {
      throw new ConflictError("messages.sent_recently")
    }
    const send: SendMessageInput = {
      template: template as MessageTemplateName,
      resource_id: message.resource_id,
      // A new send of its own: Medusa sends each key once
      key: `resend-${String(Date.now())}`,
      channels: [channel],
    }
    return new StepResponse(send)
  }
)

/**
 * "Mesajı yeniden gönder" (2026-11-06): an order's message sent again by
 * staff from its template, to the order's current e-mail or phone, through
 * sendMessageStep (deliver(): suppression, the channel, the day's quota).
 * What it came to shows in the order's history; an e-mail cannot be
 * called back, so nothing is undone.
 */
export const resendOrderMessageWorkflow = createWorkflow(
  "messaging-resend-order-message",
  (input: ResendOrderMessageInput) => {
    const send = resolveResendStep(input)
    const outcomes = sendMessageStep(send)
    const outcome = transform({ send, outcomes }, ({ send: asked, outcomes: came }) => {
      const channel = asked.channels?.[0] ?? "email"
      // No outcome: the loader found nothing to send (an invoice withdrawn, an order gone)
      return {
        channel,
        outcome: (came as Record<string, string | undefined>)[channel] ?? "unavailable",
      }
    })
    return new WorkflowResponse(outcome)
  }
)
