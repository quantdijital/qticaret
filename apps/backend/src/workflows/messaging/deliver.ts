export type SendOutcome =
  | "sent"
  | "duplicate"
  | "channel_off"
  | "invalid_recipient"
  | "suppressed"
  | "no_consent"
  | "over_quota"
  | "failed"

type Templates = typeof MESSAGE_TEMPLATES
export type VarsOf<N extends MessageTemplateName> = Templates[N]["sample"]

export interface DeliverInput<N extends MessageTemplateName> {
  template: N
  resource: { type: string; id: string }
  recipients: MessageRecipients
  receiverId: string | null
  vars: VarsOf<N>
  /** Sets one send apart from another of the same template and resource (a second reset). */
  key?: string
  /** Channels held back for this send (a checkout's texts from a flooding address, F10 M9). */
  held?: MessageChannel[]
}

type Container = Pick<MedusaContainer, "resolve">

/**
 * What Medusa's notification service does beyond its published interface
 * (2.21.2, generated by MedusaService): find a row by its key, remove one.
 */
interface NotificationRows {
  listNotifications: (
    filters: { idempotency_key: string },
    config: { take: number; select: string[] }
  ) => Promise<{ id: string; status: string }[]>
  deleteNotifications: (ids: string[]) => Promise<void>
}

/** Whether the channel can send at all: the instance's e-mail, the shop's SMS account. */
async function channelReady(container: Container, channel: MessageChannel): Promise<boolean> {
  if (channel === "email") {
    return emailTransport() !== null && (await senderAddress(container)) !== null
  }
  const account = await container
    .resolve<IntegrationCredentialsModuleService>(INTEGRATION_CREDENTIALS_MODULE)
    .read("netgsm")
  return netgsmAccountOf(account) !== null
}

function render<N extends MessageTemplateName>(
  name: N,
  channel: MessageChannel,
  vars: VarsOf<N>,
  brand: Brand,
  context: EmailContext
) {
  // The registry pairs each name with its own variables; TypeScript cannot follow N through it
  const template = MESSAGE_TEMPLATES[name] as MessageTemplate<VarsOf<N>>
  if (channel === "email" && template.email) {
    return template.email(vars, brand, context)
  }
  if (channel === "sms" && template.sms) {
    return { text: template.sms(vars, brand) }
  }
  throw new Error(`messaging: ${name} has no ${channel} form`)
}

/**
 * Sends a template's message on each of its channels the recipient has
 * an address for (adr/0036). In order: the channel is on, the address is
 * one, it is not suppressed, a commercial message has consent, the channel
 * is not held, and a new send fits the day's quota; then Medusa sends it
 * once per template, channel, resource and key. What is not sent
 * is logged with its reason and a masked address; nothing logs the
 * message itself. A provider's failure is logged and left for the retry.
 */
export async function deliver<N extends MessageTemplateName>(
  container: Container,
  input: DeliverInput<N>
): Promise<Partial<Record<MessageChannel, SendOutcome>>> {
  const template = MESSAGE_TEMPLATES[input.template]
  const messaging = container.resolve<MessagingModuleService>(MESSAGING_MODULE)
  const outcomes: Partial<Record<MessageChannel, SendOutcome>> = {}
  let brand: Brand | null = null
  for (const channel of template.channels) {
    const address = input.recipients[channel]
    if (!address) {
      continue
    }
    const fields = { template: template.name, channel, resource_id: input.resource.id }
    const notSent = (reason: SendOutcome, masked?: string) => {
      logger.info({ event: "messaging.not_sent", ...fields, reason, to: masked ?? null })
      outcomes[channel] = reason
    }
    if (!(await channelReady(container, channel))) {
      notSent("channel_off")
      continue
    }
    const to = normalizeRecipient(channel, address)
    const recipient = messaging.recipientOf(channel, address)
    if (!to || !recipient) {
      notSent("invalid_recipient")
      continue
    }
    if (await messaging.isSuppressed(channel, to)) {
      notSent("suppressed", recipient.masked)
      continue
    }
    if (template.kind === "commercial" && (await messaging.consentOf(channel, to)) !== "granted") {
      notSent("no_consent", recipient.masked)
      continue
    }
    if (input.held?.includes(channel)) {
      notSent("over_quota", recipient.masked)
      continue
    }
    const key = [template.name, channel, input.resource.id, input.key].filter(Boolean).join(":")
    const notifications = container.resolve(Modules.NOTIFICATION)
    const rows = notifications as unknown as NotificationRows
    const [previous] = await rows.listNotifications(
      { idempotency_key: key },
      { take: 1, select: ["id", "status"] }
    )
    if (previous && previous.status !== "failure") {
      outcomes[channel] = "duplicate"
      continue
    }
    if (previous) {
      // Medusa 2.21.2 sends a failed key again under an id it never stores, then fails
      // to record the result: a failed attempt is cleared and sent as a new one
      await rows.deleteNotifications([previous.id])
    }
    if (!(await withinQuota(container, channel, recipient.hash, template.name))) {
      notSent("over_quota", recipient.masked)
      continue
    }
    brand ??= await brandOf(container)
    // A commercial e-mail carries its recipient's way out, in the body and the headers
    const leave =
      template.kind === "commercial" && channel === "email" ? unsubscribeUrl(recipient.hash) : null
    const content = render(input.template, channel, input.vars, brand, { unsubscribeUrl: leave })
    try {
      const created = await notifications.createNotifications([
        {
          to,
          channel,
          template: template.name,
          // Ids only: the rendered message is never stored
          data: { resource_type: input.resource.type, resource_id: input.resource.id },
          content,
          provider_data:
            channel === "email"
              ? {
                  from_email: await senderAddress(container),
                  from_name: brand.shopName,
                  reply_to: brand.contactEmail,
                  ...(leave ? { list_unsubscribe: leave } : {}),
                }
              : { commercial: template.kind === "commercial" },
          trigger_type: template.name,
          resource_type: input.resource.type,
          resource_id: input.resource.id,
          receiver_id: input.receiverId,
          idempotency_key: key,
        },
      ])
      outcomes[channel] = created.length > 0 ? "sent" : "duplicate"
    } catch (error) {
      logger.warn({
        event: "messaging.send_failed",
        ...fields,
        to: recipient.masked,
        err: errorSummary(error),
      })
      outcomes[channel] = "failed"
    }
  }
  return outcomes
}
