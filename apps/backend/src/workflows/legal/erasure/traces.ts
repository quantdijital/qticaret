type Container = Pick<MedusaContainer, "resolve">

/** What a reader of a review or a question sees of an erased author. */
const ERASED_AUTHOR = "Anonim"

// Generated by Medusa's service factory, not declared on the module's type (2.21)
interface NotificationRecords {
  listNotifications: (
    filters: Record<string, unknown>,
    config: { select: string[] }
  ) => Promise<{ id: string }[]>
  updateNotifications: (data: { id: string; to: string }[]) => Promise<unknown>
}

/**
 * The carts: one never paid goes with its addresses; a completed one (its
 * order's) keeps its lines and loses its e-mail and addresses. The consents
 * kept against an unpaid cart go with it.
 */
async function eraseCarts(container: Container, customerId: string) {
  const carts = container.resolve<ICartModuleService>(Modules.CART)
  const rows = await carts.listCarts(
    { customer_id: customerId },
    { select: ["id", "completed_at"], relations: ["shipping_address", "billing_address"] }
  )
  const open = rows.filter((cart) => !cart.completed_at).map((cart) => cart.id)
  const completed = rows.filter((cart) => cart.completed_at)
  if (open.length > 0) {
    const legal = container.resolve<LegalModuleService>(LEGAL_MODULE)
    const messaging = container.resolve<MessagingModuleService>(MESSAGING_MODULE)
    const [consents, boxes, ages] = await Promise.all([
      legal.listLegalConsents({ cart_id: open }, { select: ["id"] }),
      messaging.listCheckoutConsents({ cart_id: open }, { select: ["id"] }),
      legal.listAgeDeclarations({ cart_id: open }, { select: ["id"] }),
    ])
    await legal.deleteLegalConsents(consents.map((row) => row.id))
    await messaging.deleteCheckoutConsents(boxes.map((row) => row.id))
    await legal.deleteAgeDeclarations(ages.map((row) => row.id))
    await carts.deleteCarts(open)
  }
  if (completed.length > 0) {
    await carts.updateCarts(
      completed.map((cart) => ({ id: cart.id, email: erasedEmail(customerId) }))
    )
    const addressIds = completed
      .flatMap((cart) => [cart.shipping_address?.id, cart.billing_address?.id])
      .filter((id): id is string => typeof id === "string")
    if (addressIds.length > 0) {
      // The columns are nullable; the DTO types them as text
      await carts.updateAddresses(
        addressIds.map((id) => ({ id, ...ERASED_ADDRESS })) as unknown as UpdateAddressDTO[]
      )
    }
  }
  return rows.length
}

/**
 * Where the customer's address was written: the messages sent (Medusa keeps
 * the recipient, never the text), the messages held back, the double
 * opt-in requests. The consent records stay: İYS asks for their proof.
 */
async function eraseMessages(container: Container, customerId: string, addresses: string[]) {
  const messaging = container.resolve<MessagingModuleService>(MESSAGING_MODULE)
  const [skips, requests] = await Promise.all([
    messaging.listMessageSkips({ receiver_id: customerId }, { select: ["id"] }),
    messaging.listConsentRequests({ customer_id: customerId }, { select: ["id"] }),
  ])
  await messaging.deleteMessageSkips(skips.map((row) => row.id))
  await messaging.deleteConsentRequests(requests.map((row) => row.id))
  const notifications = container.resolve(Modules.NOTIFICATION) as unknown as NotificationRecords
  const [byReceiver, byAddress] = await Promise.all([
    notifications.listNotifications({ receiver_id: customerId }, { select: ["id"] }),
    addresses.length
      ? notifications.listNotifications({ to: addresses }, { select: ["id"] })
      : Promise.resolve([]),
  ])
  const sent = [...new Set([...byReceiver, ...byAddress].map((row) => row.id))]
  if (sent.length > 0) {
    await notifications.updateNotifications(sent.map((id) => ({ id, to: erasedEmail(customerId) })))
  }
  return sent.length
}

/**
 * What the customer wrote in public keeps its text under an erased name:
 * reviews and questions belong to the products' pages. Their stock alerts
 * and saved products go.
 */
async function eraseContributions(container: Container, customerId: string) {
  const reviews = container.resolve<ProductReviewsModuleService>(PRODUCT_REVIEWS_MODULE)
  const qa = container.resolve<ProductQaModuleService>(PRODUCT_QA_MODULE)
  const byCustomer = { customer_id: customerId }
  const [written, asked, answered] = await Promise.all([
    reviews.listProductReviews(byCustomer, { select: ["id"] }),
    qa.listProductQuestions(byCustomer, { select: ["id"] }),
    qa.listProductAnswers(byCustomer, { select: ["id"] }),
  ])
  if (written.length > 0) {
    await reviews.updateProductReviews(
      written.map((row) => ({ id: row.id, author_name: ERASED_AUTHOR }))
    )
  }
  if (asked.length > 0) {
    await qa.updateProductQuestions(
      asked.map((row) => ({ id: row.id, author_name: ERASED_AUTHOR }))
    )
  }
  if (answered.length > 0) {
    await qa.updateProductAnswers(
      answered.map((row) => ({ id: row.id, author_name: ERASED_AUTHOR }))
    )
  }
  const alerts = container.resolve<BackInStockModuleService>(BACK_IN_STOCK_MODULE)
  const saved = container.resolve<WishlistModuleService>(WISHLIST_MODULE)
  const [waiting, kept] = await Promise.all([
    alerts.listStockAlerts(byCustomer, { select: ["id"] }),
    saved.listWishlistItems(byCustomer, { select: ["id"] }),
  ])
  await alerts.deleteStockAlerts(waiting.map((row) => row.id))
  await saved.deleteWishlistItems(kept.map((row) => row.id))
}

/**
 * Their orders from the shop's old platform (F14, adr/0042 §4), by their
 * account or an e-mail of theirs (a guest's there): the e-mail goes;
 * amounts and lines stay, as an order's do.
 */
async function eraseLegacyOrders(container: Container, customerId: string, addresses: string[]) {
  const migration = container.resolve<MigrationModuleService>(MIGRATION_MODULE)
  const [byCustomer, byAddress] = await Promise.all([
    migration.listLegacyOrders({ customer_id: customerId }, { select: ["id"] }),
    addresses.length
      ? migration.listLegacyOrders(
          { email: addresses.map((address) => address.trim().toLowerCase()) },
          { select: ["id"] }
        )
      : [],
  ])
  const ids = [...new Set([...byCustomer, ...byAddress].map((row) => row.id))]
  if (ids.length > 0) {
    await migration.updateLegacyOrders(ids.map((id) => ({ id, email: erasedEmail(customerId) })))
  }
}

/** Copies of the customer's data made for an earlier request: their files go now, not in a week. */
async function eraseExports(container: Container, customerId: string) {
  const jobs = container.resolve<AsyncJobModuleService>(ASYNC_JOB_MODULE)
  const made = await jobs.listAsyncJobs(
    { type: "customer.data_export", result_file_id: { $ne: null } },
    { select: ["id", "input", "result_file_id"] }
  )
  const theirs = made.filter(
    (job) => (job.input as { customer_id?: unknown } | null)?.customer_id === customerId
  )
  for (const job of theirs) {
    if (job.result_file_id) {
      await container.resolve(Modules.FILE).deleteFiles(job.result_file_id)
    }
  }
  if (theirs.length > 0) {
    await jobs.updateAsyncJobs(theirs.map((job) => ({ id: job.id, result_file_id: null })))
  }
}

/**
 * The customer's traces beside their orders (adr/0041 §6): carts, messages,
 * reviews and questions, stock alerts, saved products, orders from the
 * old platform, earlier copies of their data. `addresses` are the
 * e-mails messages went to (a guest's before an account). Run again, it
 * changes nothing more.
 */
export async function eraseTraces(container: Container, customerId: string, addresses: string[]) {
  const carts = await eraseCarts(container, customerId)
  const messages = await eraseMessages(container, customerId, addresses)
  await eraseContributions(container, customerId)
  await eraseLegacyOrders(container, customerId, addresses)
  await eraseExports(container, customerId)
  return { carts, messages }
}
