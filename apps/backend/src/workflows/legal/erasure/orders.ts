type Container = Pick<MedusaContainer, "resolve">

interface OrderRow {
  id: string
  created_at: string | Date
  shipping_address?: { id: string } | null
  billing_address?: { id: string } | null
  fulfillments?:
    | ({
        id: string
        data?: Record<string, unknown> | null
        delivery_address?: { id: string } | null
      } | null)[]
    | null
}

// The fulfillment module passes `updateFulfillment`'s fields to its own row (2.21)
interface FulfillmentRecords {
  updateFulfillment: (id: string, data: Record<string, unknown>) => Promise<unknown>
}

/** A stored label's file goes; a file already gone is no failure. */
async function deleteFile(container: Container, fileId: unknown): Promise<void> {
  if (typeof fileId !== "string" || !fileId) {
    return
  }
  try {
    await container.resolve(Modules.FILE).deleteFiles(fileId)
  } catch {
    logger.warn({ event: "legal.erasure_file_missing" })
  }
}

/**
 * The parcels: Medusa keeps the address each one went to, and the shop
 * keeps its label (name, address, phone on a PDF). Both go; the parcel's
 * carrier and tracking stay.
 */
async function eraseParcels(container: Container, rows: OrderRow[]) {
  const fulfillments = container.resolve(Modules.FULFILLMENT) as unknown as FulfillmentRecords
  const parcels = rows.flatMap((row) =>
    (row.fulfillments ?? []).flatMap((each) => (each ? [each] : []))
  )
  for (const parcel of parcels) {
    const data = parcel.data ?? {}
    if (data["label_file_id"]) {
      await deleteFile(container, data["label_file_id"])
      // Medusa merges `data`: the key is written over, not left out
      await fulfillments.updateFulfillment(parcel.id, { data: { label_file_id: null } })
    }
  }
  const addressIds = parcels.flatMap((parcel) =>
    parcel.delivery_address?.id ? [parcel.delivery_address.id] : []
  )
  if (addressIds.length > 0) {
    // Medusa's fulfillment module has no writer for a parcel's address (2.21:
    // `updateFulfillment` ignores it), and the tenant's one database holds it:
    // its personal columns are cleared directly, nothing else is touched
    await container
      .resolve(ContainerRegistrationKeys.PG_CONNECTION)("fulfillment_address")
      .whereIn("id", addressIds)
      .update({ ...ERASED_ADDRESS, updated_at: new Date() })
  }
}

type ActionDetails = Record<string, unknown> & {
  type?: string
  old?: { id?: string } | null
  new?: { id?: string } | null
}

// Generated by Medusa's service factory, not declared on the module's type (2.21)
interface ChangeActionWriter {
  updateOrderChangeActions: (
    data: { id: string; details: Record<string, unknown>; internal_note: null }[]
  ) => Promise<unknown>
}

const PERSONAL_PROPERTIES = new Set(["email", "shipping_address", "billing_address"])

/**
 * The order's past: Medusa's order edits keep the old e-mail and address
 * in their change actions. Those values go, and so do the staff's notes on
 * the changes; any address row they name is cleared too.
 */
async function eraseHistory(orders: IOrderModuleService, orderIds: string[]): Promise<string[]> {
  const changes = await orders.listOrderChanges({ order_id: orderIds }, { relations: ["actions"] })
  const addressIds: string[] = []
  const actions = changes.flatMap((change) =>
    change.actions.flatMap((action) => {
      const details = (action.details ?? {}) as ActionDetails
      if (!PERSONAL_PROPERTIES.has(details.type ?? "")) {
        return []
      }
      for (const side of [details.old, details.new]) {
        if (side && typeof side === "object" && typeof side.id === "string") {
          addressIds.push(side.id)
        }
      }
      // JSON fields merge on update: the keys are written over, not left out
      return [{ id: action.id, details: { old: null, new: null }, internal_note: null }]
    })
  )
  if (actions.length > 0) {
    await (orders as unknown as ChangeActionWriter).updateOrderChangeActions(actions)
  }
  if (changes.length > 0) {
    await orders.updateOrderChanges(
      changes.map((change) => ({
        id: change.id,
        internal_note: null,
        // Typed as text: emptied rather than null
        description: "",
        declined_reason: "",
      }))
    )
  }
  return addressIds
}

/**
 * The customer's orders, erased (adr/0041 §6; KK3): their e-mail and
 * addresses, the change history that kept them, the parcels' addresses
 * and labels, the staff's notes, the return requests' notes and labels,
 * the refunds' notes and the measurement consent. Amounts, lines, tax
 * and the place (city, province, country) stay for the books. A contract's
 * copy and its consent stay while the law keeps them. Medusa's own order
 * update would write the old values into a new change: the module's
 * methods are used instead. Run again, it changes nothing more.
 */
export async function eraseOrders(container: Container, customerId: string, now: Date) {
  const { data } = await container.resolve(ContainerRegistrationKeys.QUERY).graph({
    entity: "order",
    fields: [
      "id",
      "created_at",
      "shipping_address.id",
      "billing_address.id",
      "fulfillments.id",
      "fulfillments.data",
      "fulfillments.delivery_address.id",
    ],
    filters: { customer_id: customerId },
  })
  const rows = data as OrderRow[]
  if (rows.length === 0) {
    return { orders: 0 }
  }
  const orderIds = rows.map((row) => row.id)
  const orders = container.resolve<IOrderModuleService>(Modules.ORDER)
  const email = erasedEmail(customerId)
  for (const id of orderIds) {
    await orders.updateOrders(id, { email })
  }
  const pastAddresses = await eraseHistory(orders, orderIds)
  const addressIds = [
    ...new Set([
      ...rows.flatMap((row) => [row.shipping_address?.id, row.billing_address?.id]),
      ...pastAddresses,
    ]),
  ].filter((id): id is string => typeof id === "string")
  if (addressIds.length > 0) {
    await orders.updateOrderAddresses(addressIds.map((id) => ({ id, ...ERASED_ADDRESS })))
  }

  const notes = container.resolve<OrderNotesModuleService>(ORDER_NOTES_MODULE)
  const written = await notes.listOrderNotes({ order_id: orderIds }, { select: ["id"] })
  if (written.length > 0) {
    await notes.updateOrderNotes(
      written.map((note) => ({ id: note.id, body: "", removed_by: "kvkk" }))
    )
    await notes.softDeleteOrderNotes(written.map((note) => note.id))
  }
  // A fraud review keeps its rules and score; its staff note may name the buyer (adr/0044)
  const guard = container.resolve<FraudGuardModuleService>(FRAUD_GUARD_MODULE)
  const reviewed = await guard.listFraudReviews(
    { order_id: orderIds, note: { $ne: null } },
    { select: ["id"] }
  )
  if (reviewed.length > 0) {
    await guard.updateFraudReviews(reviewed.map((review) => ({ id: review.id, note: null })))
  }
  await eraseParcels(container, rows)
  const returns = container.resolve<ReturnRequestsModuleService>(RETURN_REQUESTS_MODULE)
  const asked = await returns.listReturnRequests(
    { order_id: orderIds },
    { select: ["id", "return_label_file_id"] }
  )
  for (const request of asked) {
    await deleteFile(container, request.return_label_file_id)
  }
  if (asked.length > 0) {
    await returns.updateReturnRequests(
      asked.map((request) => ({
        id: request.id,
        note: null,
        decision_note: null,
        return_label_file_id: null,
      }))
    )
  }
  const refunds = container.resolve<OrderRefundsModuleService>(ORDER_REFUNDS_MODULE)
  const refunded = await refunds.listOrderRefunds({ order_id: orderIds }, { select: ["id"] })
  if (refunded.length > 0) {
    await refunds.updateOrderRefunds(refunded.map((refund) => ({ id: refund.id, note: null })))
  }
  const conversions = container.resolve<ConversionsModuleService>(CONVERSIONS_MODULE)
  const tracked = await conversions.listTrackingConsents({ order_id: orderIds }, { select: ["id"] })
  if (tracked.length > 0) {
    await conversions.deleteTrackingConsents(tracked.map((row) => row.id))
  }

  // A contract's copy and its consent's IP address outlive the request until the law lets go
  const expired = rows
    .filter((row) => new Date(row.created_at) < cutoffOf(RETENTION_DAYS.contract, now))
    .map((row) => row.id)
  if (expired.length > 0) {
    const legal = container.resolve<LegalModuleService>(LEGAL_MODULE)
    const [copies, consents] = await Promise.all([
      legal.listLegalOrderCopies({ order_id: expired }, { select: ["id"] }),
      legal.listLegalConsents({ order_id: expired }, { select: ["id"] }),
    ])
    await legal.deleteLegalOrderCopies(copies.map((row) => row.id))
    await legal.deleteLegalConsents(consents.map((row) => row.id))
  }
  return { orders: orderIds.length, kept_contracts: orderIds.length - expired.length }
}
