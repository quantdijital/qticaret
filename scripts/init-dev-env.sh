#!/usr/bin/env bash
# Creates local env files from their env.example templates, filling generated
# secrets. Existing files are never overwritten and no value is printed.
set -euo pipefail
umask 077

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
docker_env="$root/infra/docker/.env"
backend_envs=("$root/apps/backend/.env" "$root/apps/backend/.env.test")

fail() { echo "error: $*" >&2; exit 1; }
rand() { openssl rand -hex 32; }

command -v openssl >/dev/null || fail "openssl is required"

# Fill a template: __POSTGRES_PASSWORD__ with the shared DB password and each
# __GENERATED__ with a fresh random value. Written to a temp file first so a
# failure never leaves a half-written env file behind.
render() {
  local template="$1" target="$2" pg_password="$3" tmp
  if [[ -e "$target" ]]; then
    echo "skip   ${target#"$root"/} (exists)"
    return
  fi
  tmp="$(mktemp "$target.XXXXXX")"
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line//__POSTGRES_PASSWORD__/$pg_password}"
    while [[ "$line" == *__GENERATED__* ]]; do
      line="${line/__GENERATED__/$(rand)}"
    done
    printf '%s\n' "$line"
  done <"$template" >"$tmp"
  mv -n "$tmp" "$target"
  echo "create ${target#"$root"/}"
}

if [[ -e "$docker_env" ]]; then
  pg_password="$(sed -n 's/^POSTGRES_PASSWORD=//p' "$docker_env")"
  [[ "$pg_password" =~ ^[0-9a-f]{64}$ ]] ||
    fail "POSTGRES_PASSWORD in infra/docker/.env is missing or was not generated by this script"
else
  # A new DB password would not match backend env files created earlier.
  for f in "${backend_envs[@]}"; do
    [[ -e "$f" ]] && fail "${f#"$root"/} exists but infra/docker/.env does not; remove both sides and rerun"
  done
  pg_password="$(rand)"
  render "$root/infra/docker/env.example" "$docker_env" "$pg_password"
  echo "note   an existing postgres volume keeps its old password; reset it with: pnpm db:down -v"
fi

for f in "${backend_envs[@]}"; do
  render "$root/apps/backend/env.example" "$f" "$pg_password"
done
