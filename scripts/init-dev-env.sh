#!/usr/bin/env bash
# Creates or completes local env files from their env.example templates.
# Missing files are rendered in full; existing files only get the variables
# they lack appended, so values already in use never change. Generated
# secrets are never printed.
set -euo pipefail
umask 077

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
docker_template="$root/infra/docker/env.example"
docker_env="$root/infra/docker/.env"
backend_template="$root/apps/backend/env.example"
backend_envs=("$root/apps/backend/.env" "$root/apps/backend/.env.test")
control_plane_template="$root/apps/control-plane/env.example"
control_plane_envs=("$root/apps/control-plane/.env" "$root/apps/control-plane/.env.test")
storefront_template="$root/apps/storefront/env.example"
storefront_env="$root/apps/storefront/.env.local"
# The development servers' addresses (Mailpit, the fake carriers and payment
# and SMS servers): the dev file's only. The tests start their own fakes, or
# check what is sent with no transport set; these would point them elsewhere.
# The local provisioner (adr/0061 Ek C10) is development's only: the tests use a fake.
test_skipped=" EMAIL_TRANSPORT MAILPIT_URL EMAIL_FROM PAYTR_BASE_URL ARAS_BASE_URL YURTICI_BASE_URL DHL_ECOMMERCE_BASE_URL SURAT_BASE_URL PTT_BASE_URL NETGSM_BASE_URL CP_PROVISIONER CP_LOCAL_PG_ADMIN_URL "

fail() { echo "error: $*" >&2; exit 1; }
rand() { openssl rand -hex 32; }
rel() { echo "${1#"$root"/}"; }
var_names() { sed -n 's/^\([A-Z][A-Z0-9_]*\)=.*/\1/p' "$1"; }
has_var() { [[ -e "$2" ]] && grep -q "^$1=" "$2"; }
get_var() { sed -n "s/^$1=//p" "$2"; }

command -v openssl >/dev/null || fail "openssl is required"
command -v node >/dev/null || fail "node is required"

# Secrets owned by infra/docker/.env; backend templates reference them as __NAME__.
shared_names="$(var_names "$docker_template")"

render_line() {
  local line="$1" name recipient
  for name in $shared_names; do
    [[ "$line" == *"__${name}__"* ]] && line="${line//__${name}__/$(get_var "$name" "$docker_env")}"
  done
  while [[ "$line" == *__GENERATED__* ]]; do
    line="${line/__GENERATED__/$(rand)}"
  done
  # A public age recipient whose identity is discarded (adr/0061 Ek C8)
  # An empty value is never written: the script must print one recipient
  while [[ "$line" == *__AGE_RECIPIENT__* ]]; do
    recipient="$(node "$root/scripts/age-recipient.mjs")" || fail "scripts/age-recipient.mjs failed"
    [[ "$recipient" =~ ^age1[0-9a-z]{58}$ ]] || fail "scripts/age-recipient.mjs printed no age recipient"
    line="${line/__AGE_RECIPIENT__/$recipient}"
  done
  printf '%s\n' "$line"
}

# Writes through a temp file so a failure never leaves a half-written env file.
# Variables named in the third argument (space-padded) are left out.
sync_env() {
  local template="$1" target="$2" skipped="${3:- }" tmp line name added=""
  tmp="$(mktemp "$target.XXXXXX")"
  if [[ ! -e "$target" ]]; then
    while IFS= read -r line || [[ -n "$line" ]]; do
      name="${line%%=*}"
      [[ "$line" =~ ^[A-Z][A-Z0-9_]*= && "$skipped" == *" $name "* ]] && continue
      render_line "$line"
    done <"$template" >"$tmp"
    mv -n "$tmp" "$target"
    echo "create $(rel "$target")"
    return
  fi
  cat "$target" >"$tmp"
  [[ -s "$tmp" && -n "$(tail -c 1 "$tmp")" ]] && echo >>"$tmp"
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" =~ ^[A-Z][A-Z0-9_]*= ]] || continue
    name="${line%%=*}"
    [[ "$skipped" == *" $name "* ]] && continue
    has_var "$name" "$target" && continue
    render_line "$line" >>"$tmp"
    added="$added $name"
  done <"$template"
  if [[ -z "$added" ]]; then
    rm -f "$tmp"
    echo "skip   $(rel "$target") (up to date)"
  else
    mv -f "$tmp" "$target"
    echo "update $(rel "$target") (+$added)"
  fi
}

# A new shared secret must not be generated while a backend or storefront
# file already holds a value derived from the old one; the sides would disagree.
for f in "${backend_envs[@]}" "${control_plane_envs[@]}" "$storefront_env"; do
  [[ -e "$f" ]] || continue
  for name in $shared_names; do
    has_var "$name" "$docker_env" && continue
    for dependent in $(grep -h "__${name}__" "$backend_template" "$control_plane_template" "$storefront_template" | sed 's/=.*//'); do
      has_var "$dependent" "$f" &&
        fail "$(rel "$f") has $dependent but infra/docker/.env lacks $name; remove both sides and rerun"
    done
  done
done

[[ -e "$docker_env" ]] || echo "note   an existing docker volume keeps its old password; reset with: pnpm db:down -v"
sync_env "$docker_template" "$docker_env"
for name in $shared_names; do
  [[ "$(get_var "$name" "$docker_env")" =~ ^[0-9a-f]{64}$ ]] ||
    fail "$name in infra/docker/.env is missing, duplicated or not generated by this script"
done

sync_env "$backend_template" "${backend_envs[0]}"
sync_env "$backend_template" "${backend_envs[1]}" "$test_skipped"
sync_env "$control_plane_template" "${control_plane_envs[0]}"
sync_env "$control_plane_template" "${control_plane_envs[1]}" "$test_skipped"
sync_env "$storefront_template" "$storefront_env"
